# 后面十几秒全在打 1100136，一点用都没有。
#
# 那该做什么？在窗口内把请求量顶到最大。全部已知场次的对照：
#   场次          并发  总请求  408率   有效请求*  结果
#   10-29 10:00    10     20     5%      19      ✅
#   11-04 10:00    30    143    76%      34      ✅
